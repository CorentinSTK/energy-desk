"""Write the generated blocks of worker/catalog/gie_agsi.yaml and gie_alsi.yaml (home-page map, M5).

- AGSI+: filling level and gas in storage for every EU country with storage data (fixed list below,
  checked against /api/about?show=listing on 2026-10-30).
- ALSI: send-out and inventory of every active EU LNG terminal, read from the live listing
  (/api/about?show=listing, needs GIE_API_KEY). Post-Brexit UK entries ("GB*"), the virtual Spanish
  tank ("ES*"), historical duplicates and closed terminals are left out.

Only the text between the BEGIN/END GENERATED markers is replaced; hand-written entries stay.

    uv run python -m scripts.gen_gie_catalog   # from worker/, so the worker package imports
"""

import re
import unicodedata
from pathlib import Path
from typing import Any

import httpx

from worker.config import get_settings, require

CATALOG_DIR = Path(__file__).resolve().parents[1] / "catalog"
BEGIN = "  # BEGIN GENERATED by scripts/gen_gie_catalog.py: edit the script, not this block.\n"
END = "  # END GENERATED\n"

# Countries already hand-written in gie_agsi.yaml (with injection and withdrawal): DE FR NL IT AT.
AGSI_COUNTRIES = {
    "BE": "Belgium",
    "BG": "Bulgaria",
    "CZ": "Czechia",
    "DK": "Denmark",
    "ES": "Spain",
    "HR": "Croatia",
    "HU": "Hungary",
    "LV": "Latvia",
    "PL": "Poland",
    "PT": "Portugal",
    "RO": "Romania",
    "SE": "Sweden",
    "SK": "Slovakia",
}
EXCLUDED_NAME = re.compile(r"Historical|Prior to|Post-Brexit|Virtual", re.IGNORECASE)
# Listed but never published any data (full history checked 2026-10-30); re-check when regenerating.
NEVER_PUBLISHED = {"Stade LNG Terminal 1 (FSRU Energos Force)", "Hamina LNG Terminal"}


def agsi_entries() -> str:
    out = []
    for cc, name in AGSI_COUNTRIES.items():
        code = cc.lower()
        out.append(f"""\
  - code: agsi.{code}.storage
    name: {name} gas in storage
    commodity: natgas
    region: {name}
    unit: "TWh"
    frequency: daily
    source_ref: {cc}|gasInStorage
    description: Gas in storage at the end of the gas day.
    publication_lag_days: 1
    plausible_min: 0
    plausible_max: 300
  - code: agsi.{code}.full
    name: {name} storage filling level
    commodity: natgas
    region: {name}
    unit: "%"
    frequency: daily
    source_ref: {cc}|full
    description: Gas in storage as a share of working gas volume (can exceed 100%).
    publication_lag_days: 1
    plausible_min: 0
    plausible_max: 130
""")
    return "".join(out)


def terminal_slug(name: str) -> str:
    """'Wilhelmshaven LNG Terminal 1 (FSRU Hoegh Esperanza)' → 'wilhelmshaven_1'."""
    ascii_name = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    base = re.sub(r"\(.*?\)", "", ascii_name)
    base = re.sub(r"\bLNG\b|\bTerminal\b", "", base, flags=re.IGNORECASE)
    return re.sub(r"[^a-z0-9]+", "_", base.lower()).strip("_")


def active_terminals(listing: list[dict[str, Any]]) -> list[dict[str, str]]:
    terminals = []
    for company in listing:
        for facility in company.get("facilities", []):
            country = facility["country"]
            if (
                not re.fullmatch(r"[A-Z]{2}", country)
                or country == "GB"
                or facility.get("operational_end_date")
                or EXCLUDED_NAME.search(facility["name"])
                or facility["name"] in NEVER_PUBLISHED
            ):
                continue
            terminals.append(
                {
                    "slug": terminal_slug(facility["name"]),
                    "name": facility["name"],
                    "country": country,
                    "company": facility["company"],
                    "facility": facility["eic"],
                }
            )
    slugs = [t["slug"] for t in terminals]
    duplicates = {s for s in slugs if slugs.count(s) > 1}
    if duplicates:
        raise ValueError(f"terminal slugs are not unique: {sorted(duplicates)}")
    return sorted(terminals, key=lambda t: (t["country"], t["slug"]))


def alsi_entries(terminals: list[dict[str, str]]) -> str:
    out = []
    for t in terminals:
        area = f"{t['country']}~{t['company']}~{t['facility']}"
        name = t["name"].replace('"', "'")
        out.append(f"""\
  - code: alsi.t.{t["slug"]}.send_out
    name: "{name}: send-out"
    commodity: lng
    region: {t["country"]}
    unit: "GWh/d"
    frequency: daily
    source_ref: "{area}|sendOut"
    description: Regasified LNG sent into the grid by this terminal during the gas day.
    publication_lag_days: 1
    plausible_min: 0
    plausible_max: 2000
  - code: alsi.t.{t["slug"]}.inventory
    name: "{name}: inventory"
    commodity: lng
    region: {t["country"]}
    unit: "GWh"
    frequency: daily
    source_ref: "{area}|inventory.gwh"
    description: LNG in this terminal's tanks at the end of the gas day, in energy terms.
    publication_lag_days: 1
    plausible_min: 0
    plausible_max: 15000
""")
    return "".join(out)


def replace_block(path: Path, block: str) -> None:
    text = path.read_text()
    if BEGIN in text:
        start = text.index(BEGIN)
        end = text.index(END, start) + len(END)
        text = text[:start] + BEGIN + block + END + text[end:]
    else:
        text = text.rstrip("\n") + "\n" + BEGIN + block + END
    path.write_text(text)


def main() -> None:
    key = require(get_settings().gie_api_key, "GIE_API_KEY")
    response = httpx.get(
        "https://alsi.gie.eu/api/about",
        params={"show": "listing"},
        headers={"x-key": key},
        timeout=60,
    )
    response.raise_for_status()
    terminals = active_terminals(response.json())
    replace_block(CATALOG_DIR / "gie_agsi.yaml", agsi_entries())
    replace_block(CATALOG_DIR / "gie_alsi.yaml", alsi_entries(terminals))
    print(f"AGSI: {len(AGSI_COUNTRIES)} countries; ALSI: {len(terminals)} terminals")
    for t in terminals:
        print(f"  {t['country']} {t['slug']}: {t['name']}")


if __name__ == "__main__":
    main()
