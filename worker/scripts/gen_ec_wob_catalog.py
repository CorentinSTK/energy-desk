"""Write worker/catalog/ec_wob.yaml: the Weekly Oil Bulletin series (2 products x 2 tax bases x 29
areas). Generated rather than hand-written so the 116 entries stay consistent.

    uv run python scripts/gen_ec_wob_catalog.py
"""

from pathlib import Path

CATALOG = Path(__file__).resolve().parents[1] / "catalog" / "ec_wob.yaml"

# Codes as used in the bulletin's column names (Greece is "GR" there, "EL" in EU usage).
AREAS = {
    "EU": "EU average",
    "EUR": "Euro area average",
    "AT": "Austria",
    "BE": "Belgium",
    "BG": "Bulgaria",
    "CY": "Cyprus",
    "CZ": "Czechia",
    "DE": "Germany",
    "DK": "Denmark",
    "EE": "Estonia",
    "ES": "Spain",
    "FI": "Finland",
    "FR": "France",
    "GR": "Greece",
    "HR": "Croatia",
    "HU": "Hungary",
    "IE": "Ireland",
    "IT": "Italy",
    "LT": "Lithuania",
    "LU": "Luxembourg",
    "LV": "Latvia",
    "MT": "Malta",
    "NL": "Netherlands",
    "PL": "Poland",
    "PT": "Portugal",
    "RO": "Romania",
    "SE": "Sweden",
    "SI": "Slovenia",
    "SK": "Slovakia",
}
PRODUCTS = {"euro95": "Euro-super 95 petrol", "diesel": "automotive diesel"}
TAXES = {
    "with_tax": ("pump price", "Consumer price including duties and taxes"),
    "wo_tax": ("price before taxes", "Consumer price net of duties and taxes"),
}

HEADER = """\
# GENERATED by scripts/gen_ec_wob_catalog.py: edit the script, not this file.
# European Commission Weekly Oil Bulletin, price history workbook (worker/sources/ec_wob.py).
# Terms (read 2026-10-30): the bulletin page links the Commission legal notice
# (https://commission.europa.eu/legal-notice_en): EU-owned content is licensed under CC BY 4.0
# (Commission Decision 2011/833/EU on the reuse of Commission documents); credit the source and
# indicate changes. Values are stored as published (euros per 1,000 litres); the site shows €/L.
source: ec_wob
licence:
  name: European Commission — CC BY 4.0
  url: https://commission.europa.eu/legal-notice_en
  attribution: "Source: European Commission, Weekly Oil Bulletin (CC BY 4.0); shown per litre."
licence_checked: 2026-10-30
series:
"""


def entry(kind: str, area: str, product: str) -> str:
    label, description = TAXES[kind]
    code_area = area.lower()
    return f"""\
  - code: ec_wob.{code_area}.{product}.{kind}
    name: {AREAS[area]} — {PRODUCTS[product]}, {label}
    commodity: products
    region: {AREAS[area]}
    unit: €/1000 L
    source_unit: 1000 l
    frequency: weekly
    source_ref: {kind}|{area}|{product}
    description: {description}, euros per 1,000 litres, prices in force on the bulletin date (a \
Monday), as reported by member states to the Commission.
    publication_lag_days: 4  # Monday prices, published on Thursday
    plausible_min: 200
    plausible_max: 4000
"""


def main() -> None:
    entries = [
        entry(kind, area, product) for area in AREAS for product in PRODUCTS for kind in TAXES
    ]
    CATALOG.write_text(HEADER + "".join(entries))
    print(f"wrote {len(entries)} series to {CATALOG}")


if __name__ == "__main__":
    main()
